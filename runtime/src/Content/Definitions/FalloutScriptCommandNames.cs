    // Replaces an alias in the command segment of `command` or `receiver.command`.
    internal static string Canonical(string name)
    {
        var dot = name.LastIndexOf('.');
        return Aliases.TryGetValue(name[(dot + 1)..], out var full) ? name[..(dot + 1)] + full : name;
    }

    // The lower-case full command name of a possibly qualified invocation.
    internal static string Operation(string name)
    {
        var command = name[(name.LastIndexOf('.') + 1)..];
        return (Aliases.TryGetValue(command, out var full) ? full : command).ToLowerInvariant();
    }
